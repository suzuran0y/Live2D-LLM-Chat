'use strict';
const { app } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const http = require('node:http');
const { boot } = require('../main.cjs');
const example = require('../../../configs/v2.example.json');
const ROOT = path.resolve(__dirname, '../../..');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'live2d-avatar-smoke-'));
fs.mkdirSync(path.join(root, 'electron')); app.setPath('userData', path.join(root, 'electron'));
let desktop, server, exitCode = 1;
const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
async function waitFor(check, limit = 20000) { const started = Date.now(); while (!(await check())) { if (Date.now() - started > limit) throw Error('Avatar smoke timed out'); await delay(50); } }
app.whenReady().then(async () => {
  server = http.createServer(async (request, response) => {
    for await (const _chunk of request) {};
    setTimeout(() => { if (!response.destroyed) response.end(JSON.stringify({ choices: [{ message: { content: 'fixture response' } }] })); }, 1500);
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const config = structuredClone(example); config.resources.legacyRoot = ROOT;
  config.llm.baseUrl = `http://127.0.0.1:${server.address().port}/v1`; config.llm.model = 'avatar-fixture';
  const source = path.join(root, 'config.json'); fs.writeFileSync(source, JSON.stringify(config));
  desktop = await boot({ source, dataRoot: path.join(root, 'data'), show: false });
  const actor = desktop.avatar.window; assert.ok(actor);
  const page = expression => actor.webContents.executeJavaScript(expression);
  actor.webContents.on('console-message', event => { if (event.level === 'error') console.error('Avatar console: ' + event.message); });
  await waitFor(() => desktop.avatar.phase === 'ready' || desktop.avatar.phase === 'error');
  const stats = await page('window.avatarView?.stats()'); console.log('Avatar stats: ' + JSON.stringify(stats));
  assert.equal(desktop.avatar.phase, 'ready'); assert.ok(stats.ready && stats.nonTransparentPixels > 100); assert.equal(stats.textureCount, 1); assert.ok(stats.physicsLoaded);
  assert.equal(await page('typeof window.require'), 'undefined'); assert.equal(await page('typeof window.desktop'), 'undefined');
  assert.equal(actor.webContents.getLastWebPreferences().sandbox, true);
  const unrelated = await page("fetch('/config.py').then(response => response.status)"); assert.equal(unrelated, 404);
  actor.webContents.send('avatar:mouse', { x: 1, y: 0.5 });
  await delay(160); const gaze = await page('window.avatarView.stats().values'); assert.ok(Object.values(gaze).every(Number.isFinite));
  await page("document.getElementById('avatar').dispatchEvent(new PointerEvent('pointerdown'))");
  await waitFor(async () => (await page('window.avatarView.stats()')).values.ParamEyeLOpen < 0.5);
  await waitFor(async () => (await page('window.avatarView.stats()')).values.ParamEyeLOpen > 0.95);
  const snapshotPath = path.join(ROOT, 'dist/m2-avatar-preview.png');
  fs.mkdirSync(path.dirname(snapshotPath), { recursive: true });
  await page('new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))');
  const image = await actor.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true });
  const bitmap = image.toBitmap(); let transparent = 0;
  for (let index = 3; index < bitmap.length; index += 4) if (bitmap[index] === 0) transparent++;
  assert.ok(transparent > 1000); fs.writeFileSync(snapshotPath, image.toPNG());
  desktop.avatar.pause(); await delay(100); const paused = await page('window.avatarView.stats()'); await delay(200);
  assert.equal((await page('window.avatarView.stats()')).frames, paused.frames);
  desktop.avatar.pause(); await waitFor(async () => (await page('window.avatarView.stats()')).frames > paused.frames);
  desktop.avatar.hide(); await delay(100); assert.equal((await page('window.avatarView.stats()')).paused, true);
  await desktop.avatar.toggle(); await waitFor(async () => !(await page('window.avatarView.stats()')).paused);
  actor.setSize(420, 540); await delay(120); assert.ok((await page('window.avatarView.stats()')).nonTransparentPixels > 100);
  const conversation = desktop.store.list()[0] || desktop.store.create();
  desktop.chat.send({ conversationId: conversation.id, text: '状态联动测试' });
  await waitFor(async () => (await page('window.avatarView.stats()')).state === 'thinking');
  desktop.chat.cancel(conversation.id); await waitFor(async () => (await page('window.avatarView.stats()')).state === 'idle');
  assert.equal((await page('window.avatarView.stats()')).values.ParamMouthOpenY, 0);
  await desktop.avatar.reload(); await waitFor(() => desktop.avatar.phase === 'ready' || desktop.avatar.phase === 'error');
  assert.equal(desktop.avatar.phase, 'ready'); assert.ok((await page('window.avatarView.stats()')).nonTransparentPixels > 100);
  await page("document.getElementById('avatar').getContext('webgl').getExtension('WEBGL_lose_context').loseContext()");
  await waitFor(() => desktop.avatar.phase === 'error');
  await desktop.avatar.reload(); await waitFor(() => desktop.avatar.phase === 'ready');
  // The same session can recover after a missing resource without affecting chat.
  desktop.config.config.resources.avatarModel = 'missing.model3.json'; await desktop.avatar.reload();
  await waitFor(() => desktop.avatar.phase === 'error'); assert.ok(desktop.store.list().length > 0);
  desktop.config.config.resources.avatarModel = example.resources.avatarModel; await desktop.avatar.reload();
  await waitFor(() => desktop.avatar.phase === 'ready');
  desktop.window.destroy(); assert.ok(actor.isDestroyed()); desktop = null;
  console.log('M2 smoke passed: original model, physics, transparent pixels, pause/hide/resize, chat state, reload and failure recovery.');
  console.log('Preview: ' + snapshotPath); exitCode = 0;
}).catch(error => { console.error('M2 smoke failed: ' + error.stack); }).finally(() => {
  desktop?.window.destroy(); server?.closeAllConnections(); server?.close(); app.exit(exitCode);
});
